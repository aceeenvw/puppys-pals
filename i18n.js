export function translate(key) {
    const locale = globalThis.SillyTavern?.getContext?.().getCurrentLocale?.() || 'en';
    return (locale.toLowerCase().startsWith('ru') ? ru[key] : en[key]) || en[key] || key;
}

export function translateElement(root) {
    for (const node of root.querySelectorAll('[data-pp-i18n]')) node.textContent = translate(node.dataset.ppI18n);
}
